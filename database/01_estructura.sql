-- Ejecutar como propietario del esquema dedicado FORO_USUARIOS en Oracle.
-- Crear solo una vez; no elimina ni modifica tablas preexistentes.
CREATE TABLE USUARIOS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100 CHAR) NOT NULL,
    CORREO VARCHAR2(254 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(60 CHAR) NOT NULL,
    ROL VARCHAR2(20 CHAR) NOT NULL,
    ACTIVO NUMBER(1,0) NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_CORREO UNIQUE (CORREO),
    CONSTRAINT CK_USUARIOS_ROL CHECK (ROL IN ('USUARIO', 'ADMINISTRADOR')),
    CONSTRAINT CK_USUARIOS_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT CK_USUARIOS_CORREO CHECK (CORREO = LOWER(TRIM(CORREO)))
);
