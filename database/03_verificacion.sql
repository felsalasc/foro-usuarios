-- No muestra contraseñas ni hashes. Guardar resultados para la evidencia Oracle.
SELECT SYS_CONTEXT('USERENV', 'SESSION_USER') AS ESQUEMA_ACTUAL FROM DUAL;
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME = 'USUARIOS';
SELECT COUNT(*) AS TOTAL_USUARIOS,
       SUM(CASE WHEN ACTIVO = 1 THEN 1 ELSE 0 END) AS ACTIVOS,
       SUM(CASE WHEN ACTIVO = 1 AND ROL = 'ADMINISTRADOR' THEN 1 ELSE 0 END) AS ADMINISTRADORES_ACTIVOS
FROM USUARIOS;
SELECT ID, NOMBRE, CORREO, ROL, ACTIVO FROM USUARIOS ORDER BY ID;
SELECT ROL, COUNT(*) AS CANTIDAD FROM USUARIOS WHERE ACTIVO = 1 GROUP BY ROL ORDER BY ROL;
SELECT COUNT(*) AS HASHES_CON_LONGITUD_INVALIDA FROM USUARIOS WHERE LENGTH(PASSWORD_HASH) <> 60;
SELECT CORREO, COUNT(*) AS REPETIDOS FROM USUARIOS GROUP BY CORREO HAVING COUNT(*) > 1;
SELECT CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS, VALIDATED
FROM USER_CONSTRAINTS WHERE TABLE_NAME = 'USUARIOS' ORDER BY CONSTRAINT_NAME;
SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, CHAR_LENGTH, CHAR_USED, NULLABLE
FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'USUARIOS' ORDER BY COLUMN_ID;
